// ЗАВДАННЯ 6
// Відредагувати речення, видаливши слова, що зустрічаються задану кількість разів
// =====================================================================
void task6() {
    cout << "--- ЗАВДАННЯ 6 ---" << endl;
    
    string sentence;
    int target_count;

    cout << "Введіть речення: ";
    getline(cin, sentence);

    cout << "Введіть кількість повторень слова для його видалення: ";
    cin >> target_count;

    // Розбиваємо речення на слова та рахуємо їх кількість
    stringstream ss(sentence);
    string word;
    vector<string> words;
    map<string, int> word_counts;

    while (ss >> word) {
        words.push_back(word);
        word_counts[word]++;
    }

    // Формуємо нове речення
    cout << "Відредаговане речення: ";
    bool first = true;
    for (const string& w : words) {
        // Додаємо слово лише якщо його кількість НЕ дорівнює заданій
        if (word_counts[w] != target_count) {
            if (!first) cout << " ";
            cout << w;
            first = false;
        }
    }
    cout << "\n\n";
}

