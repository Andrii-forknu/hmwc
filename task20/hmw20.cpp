// ЗАВДАННЯ 15
// Робота з вектором англійських слів та відображенням (map)
// =====================================================================
void task15() {
    cout << "--- ЗАВДАННЯ 15 ---" << endl;
    
    int n;
    cout << "Введіть кількість слів у векторі V: ";
    cin >> n;

    vector<string> V(n);
    cout << "Введіть " << n << " англійських слів через пробіл або Enter:\n";
    for (int i = 0; i < n; ++i) {
        cin >> V[i];
    }

    // M - відображення: ключ (початкова літера) -> значення (кількість слів)
    map<char, int> M; 
    
    // Додаткове відображення для сумарної довжини слів
    map<char, int> Lengths; 

    for (const string& word : V) {
        // Зчитуємо першу літеру та переводимо в нижній регістр
        char first_letter = tolower(word[0]);
        
        // ЗАУВАЖЕННЯ З УМОВИ: "При заповненні M не використовувати умовні конструкції"
        // Оператор [] автоматично створює елемент з нульовим значенням, якщо його ще немає,
        // тому ми просто інкрементуємо значення БЕЗ використання if/else.
        M[first_letter]++; 
        Lengths[first_letter] += word.length();
    }

    cout << "\nРезультати (в алфавітному порядку літер):\n";
    // map автоматично сортує елементи за ключем (в нашому випадку - за алфавітом)
    for (auto const& pair : M) {
        char letter = pair.first;
        int count = pair.second;
        int total_length = Lengths[letter];

        // Виводимо літеру, відразу після неї довжину, а потім кількість (за умовою)
        cout << "Літера '" << letter 
             << "' -> Сумарна довжина слів: " << total_length 
             << ", Кількість слів: " << count << endl;
    }
}

