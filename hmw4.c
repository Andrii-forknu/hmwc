#include <stdio.h>
#include <stdlib.h>

// --- Задача 19(б) ---
// Обчислення добутку p = (1 - 1/2^2)(1 - 1/3^2)...(1 + 1/n^2)
void task_19b() {
    printf("\n--- Задача 19(б): Обчислення добутку ---\n");
    int n;
    printf("Введіть n (n > 2): ");
    scanf("%d", &n);

    if (n <= 2) {
        printf("Помилка: n повинно бути більше 2.\n");
        return;
    }

    double p = 1.0;
    // Обчислюємо члени з мінусом від 2 до n-1
    for (int i = 2; i < n; i++) {
        p *= (1.0 - 1.0 / (i * i));
    }
    
    // Останній член згідно з умовою на фото має знак "+"
    // Примітка: ймовірно, в підручнику друкарська помилка і мав бути "-", 
    // але реалізуємо точно за записом:
    p *= (1.0 + 1.0 / (n * n));

    printf("Результат добутку p = %f\n", p);
}

// --- Задача 22 ---
// Визначення кількості елементів, які більші за своїх сусідів
void task_22() {
    printf("\n--- Задача 22: Локальні максимуми ---\n");
    int n;
    printf("Введіть кількість чисел n: ");
    scanf("%d", &n);

    if (n < 3) {
        printf("Для наявності обох сусідів (попереднього і наступного) треба мінімум 3 числа.\n");
        return;
    }

    int *arr = (int *)malloc(n * sizeof(int));
    printf("Введіть %d цілих чисел:\n", n);
    for (int i = 0; i < n; i++) {
        scanf("%d", &arr[i]);
    }

    int count = 0;
    // Перевіряємо елементи від другого до передостаннього
    for (int i = 1; i < n - 1; i++) {
        if (arr[i] > arr[i - 1] && arr[i] > arr[i + 1]) {
            count++;
        }
    }

    printf("Кількість чисел, більших за обох сусідів: %d\n", count);
    free(arr);
}

int main() {
    // Для коректного відображення символів в деяких консолях
    // system("chcp 65001 > nul"); 

    task_19b();
    task_22();

    return 0;
}